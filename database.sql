create table if not exists public.transactions (
  id bigint generated by default as identity primary key,
  telegram_user_id bigint not null,
  type text not null check (type in ('income', 'expense')),
  amount numeric(12,2) not null check (amount > 0),
  note text not null default '未分类',
  created_at timestamptz not null default now()
);

alter table public.transactions enable row level security;

-- This starter accesses the table only from the Vercel server using a Supabase secret key.
-- Do NOT put the Supabase secret key in browser/client-side code.
grant select, insert on public.transactions to service_role;
